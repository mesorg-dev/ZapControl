#!/usr/bin/env python3
"""Resolve Roblox-related hosts and write roblox-ips.json for your GitHub repo.

Usage:
  python3 scripts/update_roblox_ips.py -o roblox-ips.json

Then commit the file to the repo your zapret-gui clients pull from.
"""
from __future__ import annotations

import argparse
import datetime
import json
import socket
import sys

DEFAULT_HOSTS = [
    "tr.rbxcdn.com",
    "cdn.rbxcdn.com",
    "images.rbxcdn.com",
    "content.rbxcdn.com",
    "assets.rbxcdn.com",
    "api.roblox.com",
    "clientsettings.rbx.com",
    "setup.rbxcdn.com",
]


def resolve(host: str) -> list[str]:
    ips: list[str] = []
    try:
        infos = socket.getaddrinfo(host, 443, proto=socket.IPPROTO_TCP)
        for info in infos:
            ip = info[4][0]
            if ip not in ips:
                ips.append(ip)
    except OSError as e:
        print(f"  ! {host}: {e}", file=sys.stderr)
    return ips


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", default="roblox-ips.json")
    ap.add_argument("--hosts-file", help="file with one host per line (optional)")
    args = ap.parse_args()

    hosts = list(DEFAULT_HOSTS)
    if args.hosts_file:
        with open(args.hosts_file, encoding="utf-8") as f:
            hosts = [ln.strip() for ln in f if ln.strip() and not ln.startswith("#")]

    entries = []
    for h in hosts:
        print(f"resolve {h} ...")
        ips = resolve(h)
        if ips:
            print(f"  -> {', '.join(ips)}")
            entries.append({"host": h, "ips": ips})
        else:
            print("  -> (none)")

    doc = {
        "version": 1,
        "updated": datetime.datetime.now(datetime.timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z"),
        "description": "Roblox CDN IPs (auto-generated by update_roblox_ips.py)",
        "entries": entries,
    }

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"\nwrote {args.output} ({len(entries)} hosts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
